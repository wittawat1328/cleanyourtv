'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
const {chromium}=require('playwright');
(async()=>{
 const out=path.resolve(__dirname,'../artifacts/web-preview');fs.mkdirSync(out,{recursive:true});
 const browser=await chromium.launch({headless:true});
 try {
  const page=await browser.newPage({viewport:{width:1440,height:960},deviceScaleFactor:1});
  const external=[],jsErrors=[];
  page.on('request',r=>{if(!r.url().startsWith('file://'))external.push(r.url());});
  page.on('pageerror',e=>jsErrors.push(e.message));
  await page.goto(pathToFileURL(path.resolve(__dirname,'index.html')).href);
  await page.waitForTimeout(250);
  assert.match(await page.title(),/CleanYourTV/);
  async function ids(){return page.locator('#apps button.app').evaluateAll(all=>all.map(el=>el.dataset.id));}
  assert.deepEqual(await ids(),['youtube','netflix','browser','prime','disney','settings']);
  assert.equal(await page.locator('#utils button[data-id="inputs"]').count(),1);
  assert.match(await page.locator('#hero-title').textContent(),/ข้ามฟ้า/);
  await page.locator('#tv').screenshot({path:path.join(out,'tv-home-apple-inspired.png')});
  await page.keyboard.press('ArrowRight');
  assert.equal(await page.locator('.app.is-focused').getAttribute('data-id'),'netflix');
  await page.keyboard.press('ArrowRight');
  assert.equal(await page.locator('.app.is-focused').getAttribute('data-id'),'browser');
  await page.keyboard.press('ArrowDown');
  assert.equal(await page.locator('.cover.is-focused').first().getAttribute('data-zone'),'continue');
  await page.locator('.cover.is-focused').first().click();
  assert.equal(await page.locator('#overlay').evaluate(el=>el.classList.contains('open')),true);
  await page.locator('#close').click();
  assert.equal(await page.locator('#overlay').evaluate(el=>el.classList.contains('open')),false);
  await page.locator('#apps [data-id="browser"]').click();
  await page.locator('#close').click();
  await page.locator('#move-now').click();
  assert.equal(await page.locator('.app.is-moving').getAttribute('data-id'),'browser');
  await page.keyboard.press('ArrowLeft');
  assert.deepEqual(await ids(),['youtube','browser','netflix','prime','disney','settings']);
  await page.keyboard.press('Enter');
  assert.deepEqual(await ids(),['youtube','browser','netflix','prime','disney','settings']);
  await page.reload();
  assert.deepEqual(await ids(),['youtube','browser','netflix','prime','disney','settings']);
  await page.locator('#restore-order').click();
  assert.deepEqual(await ids(),['youtube','netflix','browser','prime','disney','settings']);
  await page.locator('#tv').screenshot({path:path.join(out,'tv-apps-and-movies.png')});
  await page.screenshot({path:path.join(out,'preview-controls.png'),fullPage:true});
  assert.deepEqual(external,[]);
  assert.deepEqual(jsErrors,[]);
  fs.writeFileSync(path.join(out,'report.json'),JSON.stringify({status:'PASS',checks:['offline UI','Browser default third','HDMI utility icon','D-pad focus','content card detail','move mode arrows','reorder save + persistence','restore order','no external requests','no JS errors'],layout:'Apple-inspired cinema 80%, apps 20%',note:'All movies and episodes are fictional placeholders.'},null,2));
  console.log('PASS: cinematic Home V1, navigation, drag mode, reorder persistence, screenshots');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
